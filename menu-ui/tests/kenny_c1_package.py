"""Export genuine production ImGui geometry and the actual portable PCM demos."""
from pathlib import Path
import base64, hashlib, html, json, shutil, struct, subprocess, wave, zipfile
from PIL import Image, ImageDraw, ImageFont
root=Path(__file__).resolve().parents[1];work=root/'.verification';out=root/'previews/phase_c1';out.mkdir(parents=True,exist_ok=True)
labels={
    'launcher-aurora':'Aurora / temporary K launcher',
    'launcher-anime':'Anime / temporary K launcher (no custom artwork)',
    'launcher-classic':'Classic / temporary K launcher',
    'opening':'Opening transition / actual production UI',
    'player':'Opened / Player ESP',
    'closing':'Closing transition / controls disabled',
    'settings':'Settings / audio unavailable on this host',
    'settings-640':'Settings / 640 × 360, scrolled',
    'audio-test-settings':'Settings / real portable PCM test sink; NOT Android playback',
}
captures=[work/('c1-'+n+'.draw') for n in labels]
assert all(p.exists() for p in captures)
subprocess.run([str(work/'kenny_host_rasterize'),str(work/'phase_b-atlas.rgba'),*map(str,captures)],check=True,timeout=60,stdout=subprocess.DEVNULL)
for name,p in zip(labels,captures):
    raw=p.with_suffix('.rgba').read_bytes();w,h=struct.unpack_from('<ii',raw)
    assert (w,h)==((640,360) if name=='settings-640' else (1920,872)) and len(raw)==8+w*h*4
    Image.frombytes('RGBA',(w,h),raw[8:]).save(out/(name+'.png'))
    with Image.open(out/(name+'.png')) as image: image.verify()
    with Image.open(out/(name+'.png')) as image: image.load()
# Enlarge the actual launcher crop, not a replacement rendering.
sheet=Image.new('RGB',(1050,440),(8,7,10));draw=ImageDraw.Draw(sheet)
font=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',22)
for i,name in enumerate(['launcher-aurora','launcher-anime','launcher-classic']):
    image=Image.open(out/(name+'.png')).convert('RGB')
    # Detect the actual bounded launcher pixels against the neutral raster backdrop.
    base=image.getpixel((0,0));mask=image.convert('RGB');from PIL import ImageChops
    bounds=ImageChops.difference(mask,Image.new('RGB',mask.size,base)).getbbox();assert bounds
    x,y=i*350,50;draw.text((x+18,16),name.replace('launcher-','').title(),font=font,fill='#F6D5DD')
    image=image.crop((max(0,bounds[0]-8),max(0,bounds[1]-8),min(mask.width,bounds[2]+8),min(mask.height,bounds[3]+8)))
    image.thumbnail((300,300));factor=min(300/image.width,300/image.height)
    image=image.resize((int(image.width*factor),int(image.height*factor)),Image.Resampling.NEAREST)
    sheet.paste(image,(x+20,y));draw.text((x+18,380),'Actual native crop × enlarged',font=font,fill='#ADA3A8')
sheet.save(out/'launcher-detail.png');labels['launcher-detail']='Three temporary launchers / enlarged native crops'
for profile in ['aurora','classic']:
    source=work/('c1-'+profile+'.wav');destination=out/(profile+'-sounds.wav');shutil.copyfile(source,destination)
    with wave.open(str(destination)) as audio:
        assert audio.getframerate()==48000 and audio.getnchannels()==1 and audio.getsampwidth()==2 and audio.getnframes()==144000
    subprocess.run(['ffmpeg','-v','error','-i',str(destination),'-f','null','-'],check=True,timeout=15)
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
sources=['jni/main.cpp','jni/Android.mk',*map(str,Path('jni').glob('Kenny*.h')),'tests/kenny_c1_check.cpp','tests/kenny_audio_check.cpp','tests/kenny_host_rasterize.cpp']
manifest={'parent_commit':'5fa7574','renderer':'Actual production C++/ImGui UI, original extracted bindings and embedded fonts; native draw data CPU-rasterized. Not Android captures. Audio WAVs are generated by the actual portable PCM mixer, not Android playback.',
'source_sha256':{str(p):sha(root/p) for p in sources},'images':{n+'.png':{'sha256':sha(out/(n+'.png')),'size':list(Image.open(out/(n+'.png')).size)} for n in labels},'audio':{n+'-sounds.wav':sha(out/(n+'-sounds.wav')) for n in ['aurora','classic']}}
(out/'verification.json').write_text(json.dumps(manifest,indent=2)+'\n')
page='<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>KennyPvtHax — C1</title><style>body{margin:20px;background:#08070a;color:#f5f2f2;font:16px system-ui}img{max-width:100%;height:auto}article{margin:30px 0}a{color:#f0a5b3}</style><h1>Phase C / Checkpoint C1</h1><p>Actual C++ / ImGui host renders. Android audio compilation and playback remain unverified. Host settings honestly disable playback controls; the separately labeled PCM-test settings capture uses the real portable mixer. No custom logo or voice recording is invented.</p>'
for name,label in labels.items():
    uri='data:image/png;base64,'+base64.b64encode((out/(name+'.png')).read_bytes()).decode()
    page+=f'<article><h2>{html.escape(label)}</h2><a href="{uri}" download="{name}.png">Download PNG</a><br><img src="{uri}" alt="{html.escape(label)}"></article>'
for profile in ['aurora','classic']:
    uri='data:audio/wav;base64,'+base64.b64encode((out/(profile+'-sounds.wav')).read_bytes()).decode()
    page+=f'<h2>{profile.title()} / actual PCM demo</h2><p>Menu open, close, checkbox on/off, button, primary/secondary navigation, theme change, in that order. 35% UI gain. Your browser plays this WAV; Android OpenSL ES is not being tested here.</p><audio controls src="{uri}"></audio>'
(out/'index.html').write_text(page+'</html>')
(out/'README.txt').write_text('Actual native ImGui host images and genuine 48kHz/16-bit mono PCM audio demos.\nOpen index.html offline. Individual PNG and WAV files are provided.\nThe labeled audio-test-settings image uses the real portable mixer. Other settings images correctly show the unavailable host playback backend.\nNo Android build/playback, custom logo, voice pack or C2 claim.\n')
with zipfile.ZipFile(out/'kennypvthax-c1-previews.zip','w',zipfile.ZIP_DEFLATED) as z:
    for p in sorted(out.iterdir()):
        if p.suffix!='.zip':z.write(p,p.name)
with zipfile.ZipFile(out/'kennypvthax-c1-previews.zip') as z:assert z.testzip() is None and len(z.namelist())==15
print('PASS C1 export: 10 PNGs fully decoded, 2 original mixer WAVs fully decoded, source/hash provenance, self-contained image/audio viewer and 15-entry ZIP.')
